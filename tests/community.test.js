import assert from 'node:assert/strict'
import { once } from 'node:events'
import { test } from 'node:test'
import { MongoMemoryServer } from 'mongodb-memory-server'
import { createApp } from '../src/app.js'
import { readConfig } from '../src/config/env.js'
import { createClient, initializeDatabase } from '../src/database/mongo.js'
import { createAuthRepository } from '../src/modules/auth/repository.js'
import { createActivityRepository } from '../src/modules/activities/repository.js'
import { createChatRepository } from '../src/modules/chat/repository.js'
import { newToken, hashToken } from '../src/modules/auth/token.js'

test('account settings, real notifications, ratings, reporting and bilateral blocking', async t => {
  const mongo = await MongoMemoryServer.create(); t.after(() => mongo.stop())
  const client = createClient(readConfig({ MONGODB_URI: mongo.getUri('community') })); await client.connect(); t.after(() => client.close())
  const db = client.db(); await initializeDatabase(db)
  const auth = createAuthRepository(db), activities = createActivityRepository(db), chat = createChatRepository(db), users = [], tokens = []
  for (let i = 0; i < 4; i++) {
    const user = await auth.createUser({ name: 'Community ' + i, email: `community${i}@example.com`, passwordHash: 'hidden' }); users.push(user)
    await db.collection('users').updateOne({ id: user.id }, { $set: { email_verified: true, ...(i === 3 ? { role: 'admin' } : {}) } })
    const token = newToken(); tokens.push(token); await auth.createSession({ userId: user.id, tokenHash: hashToken(token), expiresAt: new Date(Date.now() + 600000) })
  }
  const server = createApp(readConfig({}), { authRepository: auth, activityRepository: activities, chatRepository: chat }).listen(0, '127.0.0.1'); await once(server, 'listening'); t.after(() => new Promise(resolve => server.close(resolve)))
  const base = 'http://127.0.0.1:' + server.address().port
  const req = async (path, method = 'GET', body, user = 0) => { const response = await fetch(base + '/api' + path, { method, headers: { Authorization: 'Bearer ' + tokens[user], 'Content-Type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); return { status: response.status, body: response.status === 204 ? null : await response.json() } }
  const draft = { title: 'Community Trip', description: 'Real feature coverage', category: 'Cà phê', location: 'Hà Nội', startsAt: '2099-01-01T02:00:00.000Z', endsAt: '2099-01-01T04:00:00.000Z', estimatedCost: 0, maxParticipants: 6 }
  let activity, direct, group
  await t.test('settings persist per user and enforce invitation and private message rules', async () => {
    const changed = await req('/community/settings', 'PATCH', { allowFriendRequests: false, directMessages: 'friends', discoverable: false }, 1)
    assert.equal(changed.status, 200); assert.equal(changed.body.settings.discoverable, false)
    assert.equal((await req('/community/settings')).body.settings.discoverable, true)
    assert.equal((await req('/friends/search?q=Community')).body.items.some(user => user.id === users[1].id), false)
    assert.equal((await req('/friends/requests', 'POST', { userId: users[1].id })).status, 403)
    assert.equal((await req('/conversations', 'POST', { type: 'direct', userId: users[1].id })).status, 403)
    assert.equal((await req('/community/settings', 'PATCH', { role: 'admin' })).status, 400)
    assert.equal((await req('/community/settings', 'PATCH', { notifyActivity: 'yes' })).status, 400)
    await req('/community/settings', 'PATCH', { allowFriendRequests: true, directMessages: 'everyone', discoverable: true }, 1)
    direct = (await req('/conversations', 'POST', { type: 'direct', userId: users[1].id })).body.conversation
    await req('/community/settings', 'PATCH', { directMessages: 'friends' }, 1)
    assert.equal((await req(`/conversations/${direct.id}/messages`, 'POST', { text: 'blocked by preferences', clientMessageId: 'privacy-check' })).status, 403)
    await req('/community/settings', 'PATCH', { directMessages: 'everyone' }, 1)
  })
  await t.test('notifications are generated by actual requests, approvals, chat and host actions', async () => {
    activity = (await req('/activities', 'POST', draft)).body.activity
    const joined = await req(`/activities/${activity.id}/join-requests`, 'POST', {}, 1); assert.equal(joined.status, 201)
    const notice = (await req('/community/notifications')).body.items.find(item => item.type === 'activity'); assert.ok(notice)
    assert.equal((await req(`/community/notifications/${notice.id}/read`, 'PATCH', {}, 2)).status, 404)
    assert.equal((await req(`/community/notifications/${notice.id}/read`, 'PATCH', {})).status, 204)
    assert.equal((await req('/community/notifications')).body.unreadCount, 0)
    await req(`/activities/${activity.id}/join-requests/${joined.body.request.id}`, 'PATCH', { status: 'approved' })
    group = (await req('/conversations', 'POST', { type: 'group', activityId: activity.id })).body.conversation
    const sent = { text: 'A real message', clientMessageId: 'one-message' }
    await req(`/conversations/${group.id}/messages`, 'POST', sent); await req(`/conversations/${group.id}/messages`, 'POST', sent)
    const messages = (await req('/community/notifications', 'GET', undefined, 1)).body.items.filter(item => item.type === 'message'); assert.equal(messages.length, 1); assert.equal(messages[0].text, sent.text)
    const lastMessage = (await req(`/conversations/${group.id}/messages`, 'GET', undefined, 1)).body.items[0]
    await req(`/conversations/${group.id}/read`, 'PATCH', { messageId: lastMessage.id }, 1)
    assert.ok((await req('/community/notifications', 'GET', undefined, 1)).body.items.find(item => item.id === messages[0].id).readAt)
    assert.equal((await req('/community/notifications', 'GET', undefined, 2)).body.total, 0)
    await req('/community/settings', 'PATCH', { notifyMessages: false }, 1)
    await req(`/conversations/${group.id}/messages`, 'POST', { text: 'No notification', clientMessageId: 'two-message' })
    assert.equal((await req('/community/notifications', 'GET', undefined, 1)).body.items.filter(item => item.type === 'message').length, 1)
    await req(`/activities/${activity.id}/confirm-schedule`, 'POST', { version: (await req(`/activities/${activity.id}`)).body.activity.version })
    await req(`/activities/${activity.id}/start`, 'POST', {})
    for (const user of users.slice(0, 2)) await req(`/activities/${activity.id}/attendance/${user.id}`, 'PATCH', { status: 'present' })
    await req(`/activities/${activity.id}/complete`, 'POST', {})
    assert.ok((await req('/community/notifications', 'GET', undefined, 1)).body.items.some(item => item.title === 'Hoạt động đã kết thúc'))
    await req('/community/notifications/read', 'PATCH', {}, 1); assert.equal((await req('/community/notifications', 'GET', undefined, 1)).body.unreadCount, 0)
  })
  await t.test('ratings require completed membership and valid targets; retries do not duplicate scores', async () => {
    const rating = { score: 5, comment: 'A helpful host', members: [{ userId: users[0].id, score: 4 }] }
    assert.equal((await req(`/community/ratings/${activity.id}`, 'POST', rating, 2)).status, 403)
    assert.equal((await req(`/community/ratings/${activity.id}`, 'POST', { ...rating, members: [{ userId: users[2].id, score: 5 }] }, 1)).status, 400)
    assert.equal((await req(`/community/ratings/${activity.id}`, 'POST', { ...rating, score: 6 }, 1)).status, 400)
    const repeats = await Promise.all([req(`/community/ratings/${activity.id}`, 'POST', rating, 1), req(`/community/ratings/${activity.id}`, 'POST', rating, 1)])
    assert.ok(repeats.every(result => result.status === 200))
    assert.equal((await req(`/community/ratings/${activity.id}`, 'POST', { ...rating, score: 2 }, 1)).status, 409)
    assert.equal((await req('/profile/me/reviews')).body.count, 1); assert.equal((await req('/profile/me/reviews')).body.average, 4)
    const detail = (await req(`/activities/${activity.id}`)).body.activity; assert.equal(detail.hostRating, 4); assert.equal(detail.hostCompletedActivities, 1)
    const upcoming = (await req('/activities', 'POST', { ...draft, title: 'Upcoming trip' })).body.activity
    assert.equal((await req(`/community/ratings/${upcoming.id}`)).status, 409)
  })
  await t.test('reports persist, deduplicate and can only be processed by a provisioned admin', async () => {
    const report = { activityId: activity.id, reason: 'Thông tin sai sự thật', detail: 'Please review this activity.' }
    const first = await req('/community/reports', 'POST', report, 1), again = await req('/community/reports', 'POST', report, 1)
    assert.equal(first.status, 201); assert.equal(first.body.report.id, again.body.report.id)
    assert.equal((await req('/community/reports')).body.items.length, 0)
    assert.equal((await req('/community/moderation/reports')).status, 403)
    assert.equal((await req('/community/moderation/reports', 'GET', undefined, 3)).body.items.length, 1)
    assert.equal((await req(`/community/moderation/reports/${first.body.report.id}`, 'PATCH', { status: 'resolved', hideActivity: false }, 3)).status, 200)
    assert.equal((await req('/community/reports', 'GET', undefined, 1)).body.items[0].status, 'resolved')
  })
  await t.test('bilateral blocks revoke direct chat and invitations but preserve existing group membership', async () => {
    assert.equal((await req(`/community/blocks/${users[0].id}`, 'PUT', {}, 1)).status, 204)
    assert.equal((await req(`/conversations/${direct.id}`)).status, 403)
    assert.equal((await req(`/conversations/${direct.id}/messages`, 'POST', { text: 'Should fail', clientMessageId: 'blocked-message' })).status, 403)
    assert.equal((await req('/friends/requests', 'POST', { userId: users[1].id })).status, 403)
    assert.equal((await req(`/profile/${users[1].id}`)).status, 403)
    assert.equal((await req(`/conversations/${group.id}`, 'GET', undefined, 1)).status, 200)
    assert.equal((await req('/community/blocks', 'GET', undefined, 1)).body.items[0].userId, users[0].id)
    assert.equal((await req(`/community/blocks/${users[0].id}`, 'DELETE', undefined, 1)).status, 204)
    assert.equal((await req(`/conversations/${direct.id}`)).status, 200)
  })
})
